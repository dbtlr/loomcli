import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { afterEach, expect, test } from 'vite-plus/test';

import { checkApi } from '../../../scripts/check-api.mjs';

const trees: string[] = [];
afterEach(() => {
  for (const root of trees.splice(0)) {
    rmSync(root, { force: true, recursive: true });
  }
});

/** A self-contained declaration package, with no upward configuration lookup. */
function fixture(declaration: string, extra: Record<string, string> = {}) {
  const root = mkdtempSync(join(tmpdir(), 'loom-api-'));
  trees.push(root);
  const files = {
    'dist/index.d.ts': declaration,
    'package.json': JSON.stringify({
      exports: { '.': { types: './dist/index.d.ts' } },
      name: 'fixture',
    }),
    ...extra,
  };
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  const config = { directory: '.', entries: {}, modules: [] };
  return { config, root };
}

const tagged = '/** A value. @public */\nexport declare const value: string;\n';

test('an untagged export fails with its name, file, and line', () => {
  const { config, root } = fixture('/** A value. */\nexport declare const value: string;');
  expect(checkApi(root, [config], { update: true })).toEqual([
    expect.stringMatching(/dist\/index.d.ts:2: ae-missing-release-tag: value:/u),
  ]);
});

test.each(['@unknownTag', '@internal', '@beta', '@alpha'])(
  'rejects the undefined or disabled tag %s',
  (tag) => {
    const { config, root } = fixture(
      `/** A value. @public ${tag} */\nexport declare const value: string;`,
    );
    const id = tag === '@unknownTag' ? 'tsdoc-undefined-tag' : 'tsdoc-unsupported-tag';
    expect(
      checkApi(root, [config], { update: true }).some((line) => line.includes(`${id}: value:`)),
    ).toBe(true);
  },
);

test('other Extractor messages fail instead of being silently ignored', () => {
  const { config, root } = fixture(
    '/** A value. @public @beta */\nexport declare const value: string;',
  );
  expect(
    checkApi(root, [config], { update: true }).some((line) =>
      line.includes('ae-extra-release-tag'),
    ),
  ).toBe(true);
});

test('a changed surface fails against its committed report', () => {
  const { config, root } = fixture(tagged);
  expect(checkApi(root, [config], { update: true })).toEqual([]);
  writeFileSync(join(root, 'dist/index.d.ts'), tagged.replace('string', 'number'));
  expect(checkApi(root, [config])).toEqual([expect.stringContaining('api-report-changed')]);
});

test('a fully tagged fixture passes against its committed report', () => {
  const report = [
    '## API Report File for "fixture"',
    '',
    '> Do not edit this file. It is a report generated by [API Extractor](https://api-extractor.com/).',
    '',
    '```ts',
    '',
    '// @public',
    'export const value: string;',
    '',
    '// (No @packageDocumentation comment for this package)',
    '',
    '```',
    '',
  ].join('\n');
  const { config, root } = fixture(tagged, { 'api/index.api.md': report });
  expect(checkApi(root, [config])).toEqual([]);
});

test('--update writes a missing report and rewrites a changed report', () => {
  const { config, root } = fixture(tagged);
  expect(checkApi(root, [config])).toEqual([expect.stringContaining('api-report-changed')]);
  expect(checkApi(root, [config], { update: true })).toEqual([]);
  expect(readFileSync(join(root, 'api/index.api.md'), 'utf8')).toContain('const value: string');
  writeFileSync(join(root, 'dist/index.d.ts'), tagged.replace('string', 'number'));
  expect(checkApi(root, [config], { update: true })).toEqual([]);
  expect(readFileSync(join(root, 'api/index.api.md'), 'utf8')).toContain('const value: number');
  expect(readFileSync(join(root, 'api/index.api.md'), 'utf8')).not.toContain('\r');
});

test('forgotten exports fail unless allowlisted, and unused allowlist entries fail', () => {
  const { config, root } = fixture(
    "import type { Hidden } from './hidden.js';\n/** A function. @public */\nexport declare function get(): Hidden;",
    {
      'dist/hidden.d.ts':
        '/** A hidden shape. @public */\nexport interface Hidden {\n/** A value. */\nvalue: string;\n}',
    },
  );
  expect(checkApi(root, [config], { update: true })).toEqual([
    expect.stringContaining('ae-forgotten-export: Hidden:'),
  ]);
  const allowed = {
    ...config,
    entries: { '.': { forgottenExports: { Hidden: 'Internal computation.' } } },
  };
  expect(checkApi(root, [allowed], { update: true })).toEqual([]);
  writeFileSync(join(root, 'dist/index.d.ts'), tagged);
  expect(checkApi(root, [allowed], { update: true })).toEqual([
    expect.stringContaining('stale-forgotten-export: Hidden:'),
  ]);
});

test('external re-exports require a named reason even though Extractor reports no message', () => {
  const { config, root } = fixture("export type { External } from 'external';", {
    'node_modules/external/index.d.ts': 'export interface External { value: string }',
    'node_modules/external/package.json': JSON.stringify({ name: 'external', types: 'index.d.ts' }),
  });
  const permittedImport = { ...config, modules: ['external'] };
  expect(checkApi(root, [permittedImport], { update: true })).toEqual([
    expect.stringContaining('api-external-export: External:'),
  ]);
  const allowed = {
    ...permittedImport,
    entries: { '.': { externalExports: { External: 'Follows the upstream contract.' } } },
  };
  expect(checkApi(root, [allowed], { update: true })).toEqual([]);
});

test("a dependency's typings that import a source file do not fail the check", () => {
  const { config, root } = fixture(
    "import type { External } from 'external';\n/** A value. @public */\nexport declare const value: External;\n",
    {
      'node_modules/external/index.d.cts': "export type { External } from './types.cts';",
      'node_modules/external/package.json': JSON.stringify({
        name: 'external',
        types: 'index.d.cts',
      }),
      'node_modules/external/types.cts': 'export interface External { value: string }',
    },
  );
  const result = checkApi(root, [{ ...config, modules: ['external'] }], { update: true });
  expect(result.filter((line) => line.includes('ae-wrong-input-file-type'))).toEqual([]);
});

