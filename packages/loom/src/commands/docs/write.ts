import { lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import type { ActionHandler } from '@loomcli/core';
import { array, nullable, strictObject, string } from 'valibot';

import { readApplicationProjection } from '../../helpers/application-exports.js';
import { packagePaths } from '../../helpers/loom-config.js';
import { authorFileInTheWay, docsUnavailable, wroteDocs } from '../../helpers/messages.js';
import { existingModule, shown } from '../../helpers/modules.js';
import { packageDirectory } from '../../helpers/package-directory.js';
import { report } from '../../helpers/report.js';
import type { docs } from './command.js';

const referenceFile = strictObject({ content: string(), name: string() });
const resultSchema = strictObject({ application: string(), files: nullable(array(referenceFile)) });

/** The last line of every generated file, which marks the file as one `loom docs` may replace. */
const marker = '<!-- Generated by loom docs. -->';

/** The file's text as loom docs writes it: the rendered page, a blank line, the marker, a newline. */
function withMarker(content: string): string {
  return `${content.trimEnd()}\n\n${marker}\n`;
}

/** Whether the text's last non-empty line is the marker. */
function hasMarker(text: string): boolean {
  const lines = text.split(/\r?\n/u).filter((line) => line.trim() !== '');
  return lines.at(-1) === marker;
}

/**
 * Whether loom docs may write at the path: nothing is there, or a regular file with the marker.
 * A folder, a link, or a file without the marker is not one loom docs generated.
 */
function mayWrite(path: string): boolean {
  try {
    const stats = lstatSync(path);
    return stats.isFile() && hasMarker(readFileSync(path, 'utf8'));
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
      return true;
    }
    throw error;
  }
}

/**
 * The reference owns index.md, <app>.md, and <app>-*.md directly in its directory, the three names
 * the skills plugin owns under a skill's `references/commands/`
 * (`packages/plugins/src/skills/load.ts`); change the two together.
 */
function isOwned(name: string, application: string): boolean {
  return (
    name === 'index.md' ||
    name === `${application}.md` ||
    (name.startsWith(`${application}-`) && name.endsWith('.md'))
  );
}

/** Removes each owned, marked `.md` file directly in the directory that the run did not write, and counts them. */
function removeStaleFiles(
  output: string,
  application: string,
  written: ReadonlySet<string>,
): number {
  let removed = 0;
  for (const entry of readdirSync(output, { withFileTypes: true })) {
    const path = join(output, entry.name);
    const stale = entry.isFile() && isOwned(entry.name, application) && !written.has(entry.name);
    if (stale && hasMarker(readFileSync(path, 'utf8'))) {
      rmSync(path);
      removed += 1;
    }
  }
  return removed;
}

export const writeDocs: ActionHandler<typeof docs> = async (context) => {
  await report(context, async () => {
    const { cwd } = context.host;
    const directory = packageDirectory(cwd);
    const paths = packagePaths(directory, context.provided.config);
    const path = existingModule(
      cwd,
      context.options.application === undefined
        ? paths.application
        : resolve(cwd, context.options.application),
      context.options.application === undefined ? 'paths.application' : '--application',
    );
    const result = await readApplicationProjection(
      context,
      {
        directory,
        module: shown(cwd, path),
        path,
        projection: 'docs',
        reader: 'read-application',
      },
      resultSchema,
    );
    if (result.files === null) {
      throw new Error(docsUnavailable);
    }
    const output = resolve(cwd, context.args.directory);
    const files = result.files.map((file) => ({
      content: withMarker(Buffer.from(file.content, 'base64').toString('utf8')),
      name: file.name,
    }));
    // Judge every target before writing any, so an author's file stops the run with nothing changed.
    for (const file of files) {
      if (!mayWrite(join(output, file.name))) {
        const target = join(shown(cwd, output), file.name);
        throw new Error(authorFileInTheWay(target));
      }
    }
    mkdirSync(output, { recursive: true });
    for (const file of files) {
      writeFileSync(join(output, file.name), file.content);
    }
    const removed = removeStaleFiles(
      output,
      result.application,
      new Set(files.map((file) => file.name)),
    );
    return wroteDocs(output, files.length, removed);
  });
};
