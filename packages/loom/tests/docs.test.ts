test('leaves marked files under other names and removes only owned stale names', async () => {
  const root = fixture(['list']);
  const marked = 'Old\n\n<!-- Generated by loom docs. -->\n';
  for (const name of ['guide.md', 'notesx.md', 'notes-old.md', 'index.md', 'notes.md']) {
    put(root, `reference/${name}`, marked);
  }
  const result = await loom(root, ['docs', 'reference']);
  expect(result.status).toBe(0);
  expect(result.stdout).toBe(
    `Wrote 3 command reference files to ${join(root, 'reference')} and removed 1 earlier.\n`,
  );
  expect(readFileSync(join(root, 'reference/guide.md'), 'utf8')).toBe(marked);
  // A name that only starts with the application's name, with no hyphen after it, is not owned.
  expect(readFileSync(join(root, 'reference/notesx.md'), 'utf8')).toBe(marked);
  expect(existsSync(join(root, 'reference/notes-old.md'))).toBe(false);
  expect(readFileSync(join(root, 'reference/index.md'), 'utf8')).toBe(
    readFileSync(new URL('index-list.txt', expected), 'utf8'),
  );
  expect(readFileSync(join(root, 'reference/notes.md'), 'utf8')).toBe(
    readFileSync(new URL('notes.md', golden), 'utf8'),
  );
});

