test('renaming an application preserves the earlier reference and writes the new one', async () => {
  const root = fixture(['add']);
  const first = await loom(root, ['docs', 'reference']);
  expect(first.status).toBe(0);
  const before = texts(join(root, 'reference'));
  put(root, 'src/application.ts', applicationSource(['list'], 'journal'));
  let result = await loom(root, ['docs', 'reference']);
  expect(result.status).toBe(0);
  expect(result.stdout).toBe(`Wrote 3 command reference files to ${join(root, 'reference')}.\n`);
  for (const name of ['notes.md', 'notes-add.md']) {
    expect(readFileSync(join(root, 'reference', name), 'utf8')).toBe(before[name]);
  }
  const journal = texts(join(root, 'reference'));
  put(root, 'src/notes.ts', applicationSource(['add']));
  result = await loom(root, ['docs', 'reference', '--application', 'src/notes.ts']);
  expect(result.status).toBe(0);
  expect(result.stdout).toBe(`Wrote 3 command reference files to ${join(root, 'reference')}.\n`);
  expect(readFileSync(join(root, 'reference/index.md'), 'utf8')).toBe(before['index.md']);
  for (const name of ['journal.md', 'journal-list.md']) {
    expect(readFileSync(join(root, 'reference', name), 'utf8')).toBe(journal[name]);
  }
});

test('a renderer throwing a plain Error fails with the renderer diagnostic, not the module one', async () => {
  const root = fixturePackage({
    'node_modules/@loomcli/plugins/package.json':
      '{"type":"module","exports":{"./skills":"./skills.js"}}',
    'node_modules/@loomcli/plugins/skills.js':
      "export function commandReferences() { throw new Error('broken renderer'); }",
    'package.json': '{"type":"module"}',
    'src/application.ts':
      "import { Application } from '@loomcli/core'; export const app = new Application('notes').action(() => {});",
  });
  const result = await loom(root, ['docs', 'reference']);
  expect(result.status).toBe(1);
  expect(result.stderr).toContain('@loomcli/loom/command-references-failed');
  expect(result.stderr).toContain(
    '@loomcli/plugins threw while it rendered the command references of src/application.ts: Error: broken renderer\n',
  );
  expect(result.stderr).toContain(
    'Install @loomcli/plugins and @loomcli/core at one version, then run loom docs again.',
  );
  expect(result.stderr).not.toContain('threw while it loaded');
  expect(result.stderr).not.toContain('Skill files loader');
  expect(result.stderr).not.toContain('loom skills export again');
  expect(existsSync(join(root, 'reference'))).toBe(false);
});

