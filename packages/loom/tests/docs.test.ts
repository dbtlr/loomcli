test.each(['directory', 'link'])(
  'a %s at a path the run would write is refused and nothing is written',
  async (kind) => {
    const root = fixture();
    const elsewhere = 'Not generated.\n\n<!-- Generated by loom docs. -->\n';
    put(root, 'elsewhere.md', elsewhere);
    mkdirSync(join(root, 'reference'));
    if (kind === 'directory') {
      mkdirSync(join(root, 'reference/notes-list.md'));
    } else {
      symlinkSync(join(root, 'elsewhere.md'), join(root, 'reference/notes-list.md'));
    }
    const result = await loom(root, ['docs', 'reference']);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('reference/notes-list.md');
    expect(result.stderr).toContain('Move or rename it, then run loom docs again.');
    expect(readdirSync(join(root, 'reference'))).toEqual(['notes-list.md']);
    expect(lstatSync(join(root, 'reference/notes-list.md')).isDirectory()).toBe(
      kind === 'directory',
    );
    expect(readFileSync(join(root, 'elsewhere.md'), 'utf8')).toBe(elsewhere);
  },
);

test('a directory of unrelated files, dotfiles, and subfolders changes only by the generated files', async () => {
  const root = fixture();
  const unrelated: Record<string, string> = {
    '.hidden': 'Dot.\n',
    '.notes.md': 'Dot markdown.\n',
    'SKILL.md': '# A skill\n',
    'notes-extra.md': 'Mine.\n',
    'script.sh': '#!/bin/sh\n',
    'skills/review/SKILL.md': '# Review\n',
    'skills/review/notes-gone.md': 'Old.\n\n<!-- Generated by loom docs. -->\n',
    'sub/data.bin': 'Data.',
  };
  for (const [name, text] of Object.entries(unrelated)) {
    put(root, join('reference', name), text);
  }
  const before = snapshot(join(root, 'reference'));
  const result = await loom(root, ['docs', 'reference']);
  expect(result.status).toBe(0);
  const after = snapshot(join(root, 'reference'));
  for (const [name, bytes] of before) {
    expect(after.get(name)).toBe(bytes);
  }
  expect([...after.keys()].filter((name) => !before.has(name)).toSorted()).toEqual([
    'index.md',
    'notes-add.md',
    'notes-list.md',
    'notes.md',
  ]);
});

