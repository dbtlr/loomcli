#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { readDeclaredRules } from './rule-source.mjs';

/**
 * Generates the diagnostics reference, `docs/core/diagnostics.md`, from the rule declarations in
 * the packages' source: every Developer Diagnostic rule by identity, with its headline,
 * explanation, and docs link. `scripts/rule-source.mjs` reads the declarations as text, and fails,
 * naming file and line, when a declaring call is not one it can read. With `--check`, the script writes nothing and
 * fails when the committed page differs from what it would write; `pnpm check` runs it that way.
 * Run it without `--check` after adding or changing a rule.
 */

const root = fileURLToPath(new URL('../', import.meta.url));
const target = fileURLToPath(new URL('docs/core/diagnostics.md', new URL('../', import.meta.url)));

/** The packages in the order the page lists them; any other package follows, alphabetically. */
const packageOrder = [
  '@loomcli/core',
  '@loomcli/plugins',
  '@loomcli/validators',
  '@loomcli/prompts',
  '@loomcli/loom',
];

/** The page's frontmatter, generated notice, title, and opening paragraph. */
const preamble = `---
description: Every Developer Diagnostic rule Loom's packages declare, by identity, with its headline and explanation. Generated from the rule declarations in source by scripts/generate-diagnostics.mjs; pnpm check fails when it is stale.
---

<!-- Generated by scripts/generate-diagnostics.mjs. Do not edit; run \`node scripts/generate-diagnostics.mjs\`. -->

# Diagnostics reference

A [Developer Diagnostic](declaration-faults.md#developer-diagnostics) ends its banner with the identity of the rule it reports. Find that identity here to read the rule's headline and the explanation of why the rule exists. Each package lists its rules by identity.
`;

/** The package an identity belongs to: its first two segments, such as `@loomcli/core`. */
function packageOf(identity) {
  return identity.split('/').slice(0, 2).join('/');
}

/** Orders two strings by code unit, so the page does not depend on the machine's locale. */
function byText(left, right) {
  if (left === right) {
    return 0;
  }
  return left < right ? -1 : 1;
}

/** The position of a package in the page, with unlisted packages after the listed ones. */
function packageRank(name) {
  const index = packageOrder.indexOf(name);
  return index === -1 ? packageOrder.length : index;
}

/** Backslash-escapes the characters Markdown reads as markup, so the text renders as written. */
function escapeMarkdown(text) {
  return text.replaceAll(/[\\`*_[\]<>&]/gu, String.raw`\$&`);
}

/** A link destination that holds no space, parenthesis, or angle bracket Markdown would read. */
function linkDestination(url) {
  return url.replaceAll(/[\s()<>]/gu, (char) => encodeURIComponent(char));
}

/** One rule's entry: its heading, its headline and explanation, and a See line when it has docs. */
function renderRule(rule) {
  const entry = [
    `### ${rule.identity}`,
    `**${escapeMarkdown(rule.headline)}.** ${escapeMarkdown(rule.explanation)}`,
  ];
  if (rule.docs !== undefined) {
    entry.push(`See [${escapeMarkdown(rule.docs)}](${linkDestination(rule.docs)})`);
  }
  return entry;
}

/** The page's text for the given rules, sorted by package and then by identity. */
function renderDiagnostics(rules) {
  const sorted = rules.toSorted(
    (left, right) =>
      packageRank(packageOf(left.identity)) - packageRank(packageOf(right.identity)) ||
      byText(packageOf(left.identity), packageOf(right.identity)) ||
      byText(left.identity, right.identity),
  );
  const groups = Object.entries(Object.groupBy(sorted, (rule) => packageOf(rule.identity)));
  const sections = [];
  for (const [name, group] of groups) {
    sections.push(`## ${name}`);
    for (const rule of group) {
      sections.push(...renderRule(rule));
    }
  }
  return `${preamble}\n${sections.join('\n\n')}\n`;
}

/** The page the declarations give, or the message of the problem that stops the reader. */
function readPage() {
  try {
    return { text: renderDiagnostics(readDeclaredRules(root)) };
  } catch (error) {
    return { message: error instanceof Error ? error.message : String(error) };
  }
}

/** Writes the page, or with `--check` compares it with the committed one. Returns the exit code. */
function run(check) {
  const { message, text } = readPage();
  if (text === undefined) {
    process.stderr.write(`${message}\n`);
    return 1;
  }
  if (!check) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
    return 0;
  }
  if (existsSync(target) && readFileSync(target, 'utf8') === text) {
    return 0;
  }
  process.stderr.write(
    'docs/core/diagnostics.md is stale: it differs from the rule declarations in source.\nRun `node scripts/generate-diagnostics.mjs` and commit the result.\n',
  );
  return 1;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = run(process.argv.includes('--check'));
}

export { escapeMarkdown, renderDiagnostics };
