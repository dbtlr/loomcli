#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { findPackageJSON } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Generates core's Unicode tables as a JavaScript module from the data files of the pinned
 * `@rockorager/uucode` release, which reads them beside its own modules at run time. As a module,
 * the tables travel inside any bundle, whatever bundler builds it. Each array is written as base64
 * of its little-endian bytes, which the module decodes once at import, so a launch copies bytes
 * instead of building arrays from number literals, and a bundle carries far fewer bytes. With
 * `--check`, the script writes nothing and fails when the committed module differs from what it
 * would write; `pnpm check` runs it that way. Run it without `--check` after changing the pinned
 * release in core's development dependencies. The module's license header is a legal comment,
 * opened with `/*!`, so bundlers keep the notices in the bundle.
 */

const core = new URL('../packages/core/', import.meta.url);
const target = fileURLToPath(new URL('src/unicode.generated.ts', core));
const manifestPath = findPackageJSON('@rockorager/uucode', new URL('package.json', core));
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const generated = join(dirname(manifestPath), 'dist/src/generated');

/** The largest value each typed array kind holds. Every kind here is unsigned. */
const limits = { Uint16Array: 0xff_ff, Uint8Array: 0xff };

/**
 * Each table the module exports: the data file it comes from, its scalar members, and its array
 * members with the typed array kind uucode's own table module builds for each.
 */
const tables = [
  {
    arrays: { breakTable: 'Uint8Array' },
    file: 'runtime_grapheme.json',
    name: 'graphemeTable',
    scalars: ['breakStateCount', 'graphemeBreakPropertyCount'],
    summary: 'The grapheme break state machine, indexed by state and two break properties.',
  },
  {
    arrays: { stage1: 'Uint16Array', stage2: 'Uint8Array', stage3: 'Uint16Array' },
    file: 'runtime_width.json',
    name: 'widthTable',
    scalars: [
      'emojiVSFlag',
      'maxCodePoint',
      'stage1Shift',
      'stage2Mask',
      'widthMask',
      'zeroWidthFlag',
    ],
    summary: "Each code point's width and grapheme break property, in a three-stage lookup.",
  },
];

/** Member names in one fixed order, so the module and the shape check never depend on file order. */
function byName(left, right) {
  return left.localeCompare(right, 'en');
}

/** Whether a value is a whole number from zero through the limit. */
function fits(value, limit) {
  return Number.isSafeInteger(value) && value >= 0 && value <= limit;
}

/**
 * One table's members, after the data file proved it holds exactly the members the table names,
 * each of the expected shape. An unrecognized shape fails instead of writing a partial table.
 */
function read({ arrays, file, scalars }) {
  const data = JSON.parse(readFileSync(join(generated, file), 'utf8'));
  const expected = [...scalars, ...Object.keys(arrays)].toSorted(byName);
  const found = Object.keys(data).toSorted(byName);
  if (JSON.stringify(found) !== JSON.stringify(expected)) {
    throw new Error(`${file} holds ${found.join(', ')}, not ${expected.join(', ')}.`);
  }
  for (const key of scalars) {
    if (!fits(data[key], Number.MAX_SAFE_INTEGER)) {
      throw new Error(`${file} member ${key} is not a whole number.`);
    }
  }
  for (const [key, kind] of Object.entries(arrays)) {
    if (!Array.isArray(data[key]) || !data[key].every((value) => fits(value, limits[kind]))) {
      throw new Error(`${file} member ${key} is not a list of ${kind} values.`);
    }
  }
  return data;
}

/** The bytes of each value in a typed array kind, little-endian. */
const widths = { Uint16Array: 2, Uint8Array: 1 };

/** A list of values as base64 of each value's little-endian bytes. */
function encoded(values, kind) {
  const width = widths[kind];
  const bytes = Buffer.alloc(values.length * width);
  for (const [index, value] of values.entries()) {
    bytes.writeUIntLE(value, index * width, width);
  }
  return bytes.toString('base64');
}

/** One table as an exported constant, its members in key order. */
function declaration(table) {
  const data = read(table);
  const members = [...table.scalars, ...Object.keys(table.arrays)].toSorted(byName).map((key) => {
    const kind = table.arrays[key];
    if (kind === undefined) {
      return `  ${key}: ${String(data[key])},`;
    }
    return `  ${key}: decode${kind}(\n    '${encoded(data[key], kind)}',\n  ),`;
  });
  return `/** ${table.summary} */\nexport const ${table.name} = {\n${members.join('\n')}\n};\n`;
}

const header = `// Generated by scripts/generate-unicode-tables.mjs from @rockorager/uucode ${manifest.version}.
// Run \`node scripts/generate-unicode-tables.mjs\` to regenerate it; never edit it by hand.
// \`pnpm check\` fails when this file differs from what the generator writes.
/*!
The tables derive from the Unicode Character Database.
Copyright © 1991-2025 Unicode, Inc. Licensed under the Unicode License v3,
in licenses/unicode-LICENSE.txt of @loomcli/core.

They are generated from the tables of @rockorager/uucode.
Copyright (c) 2026 Tim Culverhouse. Licensed under the MIT License,
in licenses/uucode-LICENSE.md of @loomcli/core.
*/
`;

/**
 * The decoders the tables call, one per typed array kind. Each copies the decoded bytes into an
 * array of its own, since a small Buffer may share its memory with others. `Buffer` is in both
 * Node and Bun, and `Uint8Array.fromBase64` is not in every Node release core supports.
 */
const decoders = `/** The bytes a base64 string holds, in an array of their own. */
function decodeUint8Array(base64: string): Uint8Array {
  return new Uint8Array(Buffer.from(base64, 'base64'));
}

/** The 16-bit values a base64 string holds, each written little-endian. */
function decodeUint16Array(base64: string): Uint16Array {
  const bytes = Buffer.from(base64, 'base64');
  const values = new Uint16Array(bytes.length / 2);
  for (let index = 0; index < values.length; index += 1) {
    values[index] = bytes.readUInt16LE(index * 2);
  }
  return values;
}
`;

const module = [header, decoders, ...tables.map((table) => declaration(table))].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== module) {
    throw new Error(
      'packages/core/src/unicode.generated.ts is stale; run node scripts/generate-unicode-tables.mjs.',
    );
  }
} else {
  writeFileSync(target, module);
}
