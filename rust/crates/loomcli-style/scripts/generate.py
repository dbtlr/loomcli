#!/usr/bin/env python3
"""Generate the Unicode width tables and the glyph catalog from the TypeScript reference.

The reference carries both as generated TypeScript modules:

- packages/core/src/style/unicode.generated.ts, the uucode 2.2.1 tables (Unicode 17), base64;
- packages/core/src/style/glyphs.generated.ts, the pinned Inquirer figures inventory.

This script decodes the first into raw little-endian binary files under src/tables, which
src/width.rs includes at compile time, and writes the second as src/glyph.rs. Run it from any
directory with the path of the reference, the TypeScript workspace; from rust/:

    python3 crates/loomcli-style/scripts/generate.py ../typescript

Pass --check to compare the generated files with the committed ones instead of writing them.
"""

import base64
import json
import pathlib
import re
import subprocess
import sys

CRATE = pathlib.Path(__file__).resolve().parent.parent
TABLES = CRATE / "src" / "tables"
GLYPHS = CRATE / "src" / "glyph.rs"


def fail(message):
    print(message, file=sys.stderr)
    sys.exit(1)


def base64_member(source, name, kind):
    pattern = re.compile(name + r":\s*decode" + kind + r"Array\(\s*'([A-Za-z0-9+/=]*)'", re.S)
    match = pattern.search(source)
    if match is None:
        fail(f"unicode.generated.ts has no {kind} member {name}")
    return base64.b64decode(match.group(1))


def number_member(source, name):
    match = re.search(name + r":\s*(\d+),", source)
    if match is None:
        fail(f"unicode.generated.ts has no numeric member {name}")
    return int(match.group(1))


def unicode_outputs(reference):
    source = (reference / "packages/core/src/style/unicode.generated.ts").read_text(encoding="utf-8")
    numbers = {
        name: number_member(source, name)
        for name in [
            "breakStateCount",
            "graphemeBreakPropertyCount",
            "emojiVSFlag",
            "maxCodePoint",
            "stage1Shift",
            "stage2Mask",
            "widthMask",
            "zeroWidthFlag",
        ]
    }
    expected = {
        "breakStateCount": 5,
        "graphemeBreakPropertyCount": 20,
        "emojiVSFlag": 1,
        "maxCodePoint": 1114111,
        "stage1Shift": 8,
        "stage2Mask": 255,
        "widthMask": 3,
        "zeroWidthFlag": 4,
    }
    if numbers != expected:
        fail(f"unicode.generated.ts constants changed: {numbers}; update src/width.rs")
    return {
        "break_table.bin": base64_member(source, "breakTable", "Uint8"),
        "stage1.bin": base64_member(source, "stage1", "Uint16"),
        "stage2.bin": base64_member(source, "stage2", "Uint8"),
        "stage3.bin": base64_member(source, "stage3", "Uint16"),
    }


def rust_name(name):
    return name[0].upper() + name[1:]


def rust_string(text):
    return json.dumps(text, ensure_ascii=False)


def glyph_output(reference):
    source = (reference / "packages/core/src/style/glyphs.generated.ts").read_text(encoding="utf-8")
    forms_block = re.search(r"export const glyphForms = \{(.*?)\n\} as const;", source, re.S)
    order_block = re.search(r"export const glyph = Object\.freeze\(\{(.*?)\n\}\);", source, re.S)
    if forms_block is None or order_block is None:
        fail("glyphs.generated.ts changed shape")
    forms = {}
    for line in forms_block.group(1).strip().splitlines():
        match = re.fullmatch(r'\s*(\w+): \[(".*?"), (".*?")\],', line)
        if match is None:
            fail(f"unrecognized glyph form line: {line!r}")
        forms[match.group(1)] = (json.loads(match.group(2)), json.loads(match.group(3)))
    order = []
    for line in order_block.group(1).strip().splitlines():
        match = re.fullmatch(r"\s*(\w+): frame\(\['glyph', '(\w+)'\], ''\),", line)
        if match is None or match.group(1) != match.group(2):
            fail(f"unrecognized glyph line: {line!r}")
        order.append(match.group(1))
    if sorted(order) != sorted(forms):
        fail("the glyph object and glyphForms name different glyphs")
    variants = "\n".join(
        f"    /// `{name}`: `{forms[name][0]}`, or `{forms[name][1]}` in compatibility form.\n    {rust_name(name)},"
        for name in order
    )
    all_list = "\n".join(f"        Glyph::{rust_name(name)}," for name in order)
    names = "\n".join(f'            Glyph::{rust_name(name)} => "{name}",' for name in order)
    main = "\n".join(
        f"            Glyph::{rust_name(name)} => {rust_string(forms[name][0])}," for name in order
    )
    compat = "\n".join(
        f"            Glyph::{rust_name(name)} => {rust_string(forms[name][1])}," for name in order
    )
    return f"""// Generated by scripts/generate.py from the reference's glyphs.generated.ts, itself generated
// from Inquirer figures a446ea9e273864a3653a26943f59b4fbe8003796. Never edit it by hand.
//
// The inventory is MIT-licensed by Simon Boudrias (Inquirer) and Sindre Sorhus (figures); both
// notices are in this crate's licenses folder.

//! The glyph catalog: every name the pinned Inquirer figures inventory holds, with Loom's
//! `success` and `error` aliases.

/// One glyph of the catalog. Its [`Display`](std::fmt::Display) form is the unstyled marked string
/// that resolves to the main form, or to the compatibility form on the Linux console (`TERM=linux`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum Glyph {{
{variants}
}}

impl Glyph {{
    /// Every glyph, in catalog order.
    pub const ALL: &'static [Glyph] = &[
{all_list}
    ];

    /// The glyph's catalog name, as the wire spells it, such as `radioOn`.
    #[must_use]
    pub const fn name(self) -> &'static str {{
        match self {{
{names}
        }}
    }}

    /// The main form, which every destination but the Linux console selects.
    #[must_use]
    pub const fn main_form(self) -> &'static str {{
        match self {{
{main}
        }}
    }}

    /// The compatibility form, which the Linux console (`TERM=linux`) selects.
    #[must_use]
    pub const fn compatibility_form(self) -> &'static str {{
        match self {{
{compat}
        }}
    }}
}}
"""


def formatted(source):
    """The source as rustfmt writes it, so the committed file passes `cargo fmt --check`."""
    result = subprocess.run(
        ["rustfmt", "--edition", "2024"],
        input=source.encode("utf-8"),
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        fail("rustfmt rejected the generated glyph module: " + result.stderr.decode("utf-8"))
    return result.stdout


def main(arguments):
    check = "--check" in arguments
    paths = [argument for argument in arguments if argument != "--check"]
    if len(paths) != 1:
        fail("usage: generate.py [--check] <reference checkout>")
    reference = pathlib.Path(paths[0])
    outputs = {TABLES / name: data for name, data in unicode_outputs(reference).items()}
    outputs[GLYPHS] = formatted(glyph_output(reference))
    stale = []
    for path, data in outputs.items():
        if check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if stale:
        fail("stale generated files: " + ", ".join(stale))


if __name__ == "__main__":
    main(sys.argv[1:])
